export function ingredientCategory(name: string): IngredientCategory {
 return (Object.keys(groups).find(key=>groups[key].includes(name)) as IngredientCategory | undefined) ?? '水果与辅料';
}

export function normalizeIngredientQuery(value: string) {
 return value.normalize('NFKD').replace(/\p{M}/gu, '').trim().toLowerCase();
}
